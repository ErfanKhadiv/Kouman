export const DEFAULT_LANG = 'fa'
export const SUPPORTED_LANGS = Object.keys(translations)

export const translate = (lang, key, vars = {}) => {
  const template = translations[lang]?.[key] ?? translations[DEFAULT_LANG][key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`))
}
